import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const source = await readFile(path.join(root, "project-b/packages/db/prisma/domain.prisma"), "utf8");
const userIds = "userId|ownerId|inviterId|inviteeId|decidedById|assigneeId|creatorId|authorId|createdById|actorId|recipientId|generatedById|snoozedById|hostId|invitees";
// Preserve A's existing text IDs. Project/task/repository UUIDs stay UUIDs.
let mapped = source.replace(new RegExp(`^(\\s*(?:${userIds})\\s+String[^\\n]*?)\\s+@db\\.Uuid`, "gm"), "$1");
mapped = mapped.replace(/(model User \{[\s\S]*?\n\})/, (block) => block
  .replace(/(id\s+String[^\n]*?)\s+@db\.Uuid/, "$1")
  .replace(/(displayName\s+String)/, '$1 @map("name")')
  .replace(/(avatarUrl\s+String\?)/, '$1 @map("profileImage")')
  .replace(/\n\}$/, '\n  @@map("user")\n}'));
for (const [model, table] of [["Session", "WorkspaceSession"], ["Comment", "ProjectComment"], ["Notification", "ProjectNotification"]]) {
  mapped = mapped.replace(new RegExp(`model ${model} \\{[\\s\\S]*?\\n\\}`), (block) => block.replace(/\n\}$/, `\n  @@map("${table}")\n}`));
}
const banner = "// GENERATED by scripts/workspace-schema.mjs. Do not edit directly.\n";
await writeFile(path.join(root, "project-b/packages/db/prisma/schema.prisma"), banner + mapped);

// A owns the only migration history and the canonical User. B's Prisma client
// is a projection of the same physical tables, not a second database.
let models = mapped.replace(/generator client \{[\s\S]*?\n\}/, "")
  .replace(/datasource db \{[\s\S]*?\n\}/, "")
  .replace(/model User \{[\s\S]*?\n\}/, "");
for (const [from, to] of [["Session", "WorkspaceSession"], ["Comment", "ProjectComment"], ["Notification", "ProjectNotification"]]) {
  models = models.replace(new RegExp(`\\b${from}\\b`, "g"), to);
}
await writeFile(path.join(root, "prisma/workspace.prisma"), banner + models);
